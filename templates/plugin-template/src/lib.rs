use intentumdiff_plugin_sdk::tree::{SemanticNode, SemanticNodeBuilder};

const GRAMMAR_ID: &str = "{{language}}";
const LANGUAGE_IDS: &[&str] = &["{{language}}"];

fn is_interesting_line(line: &str) -> bool {
    let trimmed = line.trim();
    !trimmed.is_empty() && !trimmed.starts_with("//") && !trimmed.starts_with('#')
}

// Positions are 0-based lines and byte columns (the SDK compliance suite rejects spans
// that fall outside the source).
fn node_for_line(index: usize, line: &str) -> Option<SemanticNode> {
    if !is_interesting_line(line) {
        return None;
    }

    let line_no = index as u32;
    let trimmed = line.trim();
    Some(
        SemanticNodeBuilder::new(
            format!("0.{index}"),
            "statement",
            trimmed,
            line_no,
            0,
            line_no,
            line.len() as u32,
            "",
        )
        .build(),
    )
}

fn parse_source(source: &str) -> SemanticNode {
    let lines: Vec<&str> = source.split('\n').collect();
    let children: Vec<SemanticNode> = lines
        .iter()
        .enumerate()
        .filter_map(|(index, line)| node_for_line(index, line))
        .collect();

    let end_line = (lines.len() - 1) as u32;
    let end_col = lines.last().map_or(0, |line| line.len()) as u32;
    SemanticNodeBuilder::new("0", "source_file", GRAMMAR_ID, 0, 0, end_line, end_col, "")
        .children(children)
        .build()
}

fn process_impl(source: &str) -> String {
    serde_json::to_string(&parse_source(source))
        .unwrap_or_else(|error| format!(r#"{{"error":"serialization failed: {error}"}}"#))
}

// WIT exports are generated by wit-bindgen in real plugins. These functions
// show the shape expected by the IntentumDiff parser world.

pub fn get_parser_mode() -> &'static str {
    "full-parse"
}

pub fn grammar_id() -> &'static str {
    GRAMMAR_ID
}

pub fn language_ids() -> Vec<&'static str> {
    LANGUAGE_IDS.to_vec()
}

pub fn detect_language(filename: &str, _content: &str) -> String {
    if filename.ends_with(".{{language}}") {
        GRAMMAR_ID.to_string()
    } else {
        String::new()
    }
}

pub fn preprocess_source(source: &str) -> String {
    source.to_string()
}

pub fn process(input: &str, _language: &str, _filename: &str) -> String {
    process_impl(input)
}

pub fn trivia_node_types() -> Vec<&'static str> {
    Vec::new()
}
